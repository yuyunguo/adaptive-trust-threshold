# -------------------------
# Parameters & thresholds
# -------------------------
EVI_THRESHOLD = 0.75   # cosine threshold for evidence linking if embeddings used
L_MIN, L_MAX, L_OPT = 6, 80, 30
LAMBDA = 0.05
MAX_STEPS = 5

# -------------------------
# Helper functions
# -------------------------
def tokenize_text(t):
    return t.split()

def cosine_similarity(a, b):
    a = np.array(a); b = np.array(b)
    denom = (np.linalg.norm(a)*np.linalg.norm(b) + 1e-9)
    return float(np.dot(a,b)/denom)

def embed_texts(texts):
    if USE_EMBEDDINGS:
        return embed_model.encode(texts, show_progress_bar=False)
    else:
        # TF-IDF fallback: vectorizer must be fit on a corpus. We'll fit on combined EHR+explanations.
        raise RuntimeError("Call embed_texts_after_fit() if not using embeddings.")


# If not using embeddings, build TF-IDF on all texts
if not USE_EMBEDDINGS:
    corpus = []
    for idx,row in df.iterrows():
        corpus.extend(row['ehr_snippets'])
        corpus.append(row['ai_explanation'])
    vectorizer.fit(corpus)
    def embed_texts_after_fit(texts):
        return vectorizer.transform(texts).toarray()


