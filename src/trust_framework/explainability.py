# Component functions
# -------------------------
def evidence_linkage_score(explanation_text, ehr_evidence_texts, use_embed=USE_EMBEDDINGS):
    # split explanation into sentences (simple)
    claims = [c.strip() for c in re.split(r'[.]\s+', explanation_text.strip()) if c.strip()]
    if len(claims) == 0:
        return 0.0, []
    if use_embed:
        claim_embs = embed_texts(claims)
        evidence_embs = embed_texts(ehr_evidence_texts)
    else:
        claim_embs = embed_texts_after_fit(claims)
        evidence_embs = embed_texts_after_fit(ehr_evidence_texts)
    matched_claims = 0
    matched_pairs = []
    for j,ce in enumerate(claim_embs):
        sims = [cosine_similarity(ce, ee) for ee in evidence_embs]
        best_sim = max(sims)
        matched = best_sim >= EVI_THRESHOLD
        if matched:
            matched_claims += 1
            matched_pairs.append((claims[j], best_sim))
    return matched_claims / len(claims), matched_pairs

def reasoning_coherence_score(explanation_text, surrogate_fn, input_representation=None, n_perturbs=30):
    # heuristic count of causal connectors
    causal_terms = ['because','therefore','due to','as a result','likely','suggests','because of']
    steps = sum(1 for t in causal_terms if t in explanation_text.lower())
    steps_score = min(steps, MAX_STEPS) / MAX_STEPS
    # surrogate fidelity
    # generate perturbs (domain-specific; here we use simple random noise on a numeric vector placeholder)
    # NOTE: for real EHR, perturb by masking sentences, jittering lab values, etc.
    if input_representation is None:
        # dummy: generate random X features and model outputs to simulate fidelity
        Xp = np.random.normal(size=(n_perturbs, 5))
        y_pred = np.random.uniform(0.3, 0.9, size=n_perturbs)
        Xf = Xp
    else:
        Xp = [input_representation for _ in range(n_perturbs)]
        Xf = np.random.normal(size=(n_perturbs, 5))
        y_pred = surrogate_fn(Xp)  # user-supplied
    # fit surrogate
    try:
        model = Ridge(alpha=1.0)
        model.fit(Xf, y_pred)
        y_surr = model.predict(Xf)
        fidelity = max(0, r2_score(y_pred, y_surr))
    except Exception:
        fidelity = 0.0
    return 0.5*(steps_score + fidelity), fidelity

def conciseness_score(explanation_text):
    tokens = tokenize_text(explanation_text)
    L = len(tokens)
    if L_MIN <= L <= L_MAX:
        return 1.0
    return float(np.exp(-LAMBDA * abs(L - L_OPT)))

def specificity_actionability_score(explanation_text):
    has_value = bool(re.search(r'\b\d+(\.\d+)?\b', explanation_text))
    actions = ['order','consider','repeat','start','stop','monitor','immediate','recommend']
    has_action = any(w in explanation_text.lower() for w in actions)
    return 0.5*float(has_value) + 0.5*float(has_action)

def counterfactual_score(explanation_text):
    forms = ['may be','could be','possible','consider','alternative','might be']
    found = sum(1 for f in forms if f in explanation_text.lower())
    return min(1.0, found / len(forms))

