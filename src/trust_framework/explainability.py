# -------------------------
# Anti-gaming perturbations (evaluate delta E)
# -------------------------
def perturb_append_boilerplate(expl):
    return expl + " Note: this is an autogenerated explanation. Please verify clinically."

def perturb_add_random_numbers(expl):
    return expl + " 123 456 789"

def perturb_duplicate_claims(expl):
    return expl + " " + expl

def perturb_copy_ehr_verb(expl, ehr_snippets):
    # copy first evidence verbatim into explanation
    return expl + " Evidence: " + ehr_snippets[0]

perturbations = {
    'boilerplate': perturb_append_boilerplate,
    'random_numbers': perturb_add_random_numbers,
    'duplicate': perturb_duplicate_claims,
    'copy_ehr': perturb_copy_ehr_verb
}

anti_game_results = []
for pid, row in df.iterrows():
    base_expl = row['ai_explanation']
    ehr = row['ehr_snippets']
    base_E = res_df.loc[row['case_id'],'E']
    for pname,pfunc in perturbations.items():
        pert_expl = pfunc(base_expl) if pname!='copy_ehr' else pfunc(base_expl, ehr)
        e_evi_p, _ = evidence_linkage_score(pert_expl, ehr)
        e_coh_p, fid_p = reasoning_coherence_score(pert_expl, surrogate_fn_dummy)
        e_spec_p = specificity_actionability_score(pert_expl)
        e_conc_p = conciseness_score(pert_expl)
        e_cf_p = counterfactual_score(pert_expl)
        e_fid_p = fid_p
        E_p = (weights['evi']*e_evi_p + weights['coh']*e_coh_p + weights['spec']*e_spec_p +
               weights['conc']*e_conc_p + weights['cf']*e_cf_p + weights['fid']*e_fid_p)
        anti_game_results.append({'case_id':row['case_id'],'perturb':pname,'E_base':base_E,'E_pert':E_p,'delta':E_p-base_E})

anti_df = pd.DataFrame(anti_game_results)
display(anti_df.groupby('perturb')['delta'].describe())

plt.figure(figsize=(8,5))
sns.boxplot(x='perturb', y='delta', data=anti_df)
plt.title("Anti-gaming perturbation impact on E (delta E)")
plt.axhline(0, color='k', linestyle='--')
plt.show()

