# Compute E for all cases
# -------------------------
results = []
for idx,row in df.iterrows():
    case_id = row['case_id']
    ehr = row['ehr_snippets']
    expl = row['ai_explanation']
    # evidence linkage
    e_evi, pairs = evidence_linkage_score(expl, ehr)
    # reasoning coherence - here we use dummy surrogate (use model outputs in real impl)
    # using a surrogate_fn that returns model_pred_prob for input (sim)
    def surrogate_fn_dummy(Xp):
        return np.array([row['model_pred_prob'] for _ in range(len(Xp))])
    e_coh, fidelity = reasoning_coherence_score(expl, surrogate_fn_dummy)
    e_spec = specificity_actionability_score(expl)
    e_conc = conciseness_score(expl)
    e_cf = counterfactual_score(expl)
    e_fid = fidelity
    weights = {'evi':0.25,'coh':0.20,'spec':0.20,'conc':0.15,'cf':0.10,'fid':0.10}
    E = (weights['evi']*e_evi + weights['coh']*e_coh + weights['spec']*e_spec +
         weights['conc']*e_conc + weights['cf']*e_cf + weights['fid']*e_fid)
    results.append({
        'case_id': case_id,
        'explanation': expl,
        'e_evi': e_evi,
        'e_coh': e_coh,
        'e_spec': e_spec,
        'e_conc': e_conc,
        'e_cf': e_cf,
        'e_fid': e_fid,
        'E': E,
        'matched_pairs': pairs
    })

res_df = pd.DataFrame(results).set_index('case_id')
print(res_df.head())

