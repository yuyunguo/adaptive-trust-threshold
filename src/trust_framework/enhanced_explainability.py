@dataclass
class ExplainabilityConfig:
    """Configuration parameters for explainability scoring"""
    # Evidence linkage parameters - adjusted for realistic medical text similarity
    evidence_threshold: float = 0.3
    min_claims_for_scoring: int = 1

    # Reasoning coherence parameters
    max_reasoning_steps: int = 5
    causal_terms: Optional[List[str]] = None

    # Conciseness parameters
    optimal_length_min: int = 10
    optimal_length_max: int = 80
    optimal_length_target: int = 30
    length_penalty_lambda: float = 0.05

    # Fidelity parameters
    n_perturbations: int = 30
    surrogate_alpha: float = 1.0

    # Component weights (must sum to 1.0)
    weights: Optional[Dict[str, float]] = None

    def __post_init__(self):
        if self.causal_terms is None:
            self.causal_terms = [
                'because', 'therefore', 'due to', 'as a result', 'likely',
                'suggests', 'indicates', 'given that', 'since', 'thus'
            ]

        if self.weights is None:
            self.weights = {
                'evidence': 0.25,
                'coherence': 0.20,
                'specificity': 0.20,
                'conciseness': 0.15,
                'counterfactual': 0.10,
                'fidelity': 0.10
            }

        # Validate weights sum to 1.0
        if abs(sum(self.weights.values()) - 1.0) > 1e-6:
            raise ValueError(f"Component weights must sum to 1.0, got {sum(self.weights.values())}")

